import { useState } from "react";
import { Sparkles, TrendingUp, Users, Lightbulb } from "lucide-react";
import { Card } from "../ui/primitives";
import Button from "../ui/Button";
import { aiApi } from "../../api/client";
import { useToast } from "../../context/ToastContext";

const ICONS = {
  "Campaign Performance": TrendingUp,
  "Subscriber Health": Users,
  Recommendation: Lightbulb,
};

export default function AiInsightsPanel({ subscribers = [], campaigns = [] }) {
  const toast = useToast();
  const [items, setItems] = useState(null);
  const [generating, setGenerating] = useState(false);

  async function handleGenerate() {
    setGenerating(true);

    try {
      const metrics = {
        totalSubscribers: subscribers.length,
        activeSubscribers: subscribers.filter((s) => s.status === "active").length,
        bouncedSubscribers: subscribers.filter((s) => s.status === "bounced").length,
        unsubscribedSubscribers: subscribers.filter((s) => s.status === "unsubscribed").length,
        totalCampaigns: campaigns.length,
        sentCampaigns: campaigns.filter((c) => c.status === "sent").length,
        draftCampaigns: campaigns.filter((c) => c.status === "draft").length,
        scheduledCampaigns: campaigns.filter((c) => c.status === "scheduled").length,
        failedCampaigns: campaigns.filter((c) => c.status === "failed").length,
        cancelledCampaigns: campaigns.filter((c) => c.status === "cancelled").length,
      };

      const { data } = await aiApi.insights(metrics);
      const generated = data.data?.insights;

      if (!Array.isArray(generated) || generated.length !== 3) {
        throw new Error("Groq returned an unexpected insights response.");
      }

      setItems(generated);
      toast.success("AI insights generated with Groq.");
    } catch (err) {
      toast.error(
        err.response?.data?.message ||
        err.message ||
        "Couldn't generate AI insights. Check your Groq API configuration."
      );
    } finally {
      setGenerating(false);
    }
  }

  return (
    <Card className="p-5 border-signal-violet/20 bg-signal-violet/[0.05] flex flex-col">
      <div className="flex items-center gap-2 mb-1">
        <Sparkles size={16} className="text-signal-violet" />
        <h3 className="font-display font-semibold text-mist-100 text-sm">
          AI Campaign Insights
        </h3>
      </div>

      <p className="text-xs text-mist-400 mb-4 leading-relaxed">
        {items
          ? "Insights generated by Groq using your current account data."
          : "Generate AI recommendations based on your subscriber and campaign data."}
      </p>

      {items && (
        <div className="space-y-4 mb-4 flex-1">
          {items.map((item, i) => {
            const Icon = ICONS[item.label] || Sparkles;

            return (
              <div key={i} className="flex items-start gap-3">
                <div className="flex h-7 w-7 shrink-0 items-center justify-center rounded-full bg-signal-violet/15 mt-0.5">
                  <Icon size={13} className="text-signal-violet" />
                </div>

                <div className="min-w-0">
                  <p className="text-sm font-medium text-mist-100">
                    {item.label}
                  </p>
                  <p className="text-xs text-mist-400 leading-relaxed mt-0.5">
                    {item.text}
                  </p>
                </div>
              </div>
            );
          })}
        </div>
      )}

      <Button
        size="sm"
        loading={generating}
        onClick={handleGenerate}
        className="w-full"
      >
        {items ? "Generate New Insights" : "Generate Insights"}
      </Button>
    </Card>
  );
}
